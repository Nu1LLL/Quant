"""One-command, storage-light execution of the frozen altcoin reversal test.

Run from the repository root with:
    python3 Spot_Multi_Strategy/research/run_altcoin_reversal.py

The official ZIPs live only in memory.  Only checksum/coverage metadata and
small result summaries are written; no raw market data or full trade log is
retained.  The preregistration is a separate, earlier Git commit.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import subprocess

from altcoin_reversal_archive import ArchiveIntegrityError, load_and_audit
from altcoin_reversal_backtest import (
    DataIntegrityError,
    run_reversal_backtest,
)


ROOT = Path(__file__).resolve().parents[2]
REPORT_DIR = (ROOT / "Spot_Multi_Strategy" / "reports"
              / "mini_medallion_altcoin_volume_reversal_oos")


def _commit() -> str:
    return subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
    ).strip()


def _save(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # This is a research artifact generated by the program, not an edit to
    # source code.  Reject NaN rather than silently serializing invalid PnL.
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True,
                   allow_nan=False) + "\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-workers", type=int, default=12,
                        help="HTTP concurrency only; no strategy setting")
    args = parser.parse_args()
    result_path = REPORT_DIR / "RESULT.json"
    failure_path = REPORT_DIR / "DATA_FAILURE.json"
    if result_path.exists() or failure_path.exists():
        parser.error("a formal outcome already exists; do not rerun this history")
    commit = _commit()
    started = datetime.now(timezone.utc).isoformat()
    try:
        bundle = load_and_audit(max_workers=args.max_workers)
        # Archive checksums are persisted before calculating any returns.
        _save(REPORT_DIR / "ARCHIVE_MANIFEST.json", bundle.manifest)
        base = run_reversal_backtest(
            bundle.trade_bars, bundle.mark_bars, bundle.funding_events,
            slippage_rate=0.001,
        )
        high_slippage = run_reversal_backtest(
            bundle.trade_bars, bundle.mark_bars, bundle.funding_events,
            slippage_rate=0.0025,
        )
        stress: dict[str, dict] = {}
        held = base.report["historical_holdout"]
        if (held["sharpe"] is not None and held["sharpe"] > 1.5
                and held["profit_factor"] is not None
                and held["profit_factor"] > 1.3):
            for multiple in (3.0, 5.0):
                result = run_reversal_backtest(
                    bundle.trade_bars, bundle.mark_bars,
                    bundle.funding_events, slippage_rate=0.001,
                    leverage=multiple, base_result=base,
                )
                stress[f"{int(multiple)}x"] = result.report
        payload = {
            "status": "completed_historical_test",
            "evidence": "preregistered retrospective blind, not prospective OOS",
            "research_scope": "crypto and US equities only; this test is crypto",
            "preregistration_commit": "4ec84a3",
            "interpretation_commit": "2a9cbe9",
            "code_commit": commit,
            "started_utc": started,
            "finished_utc": datetime.now(timezone.utc).isoformat(),
            "official_archive_count": bundle.manifest["archive_count"],
            "base_1x": base.report,
            "slippage_025pct_1x": high_slippage.report,
            "conditional_leverage": stress,
            "formal_gate_passed": bool(base.report["gate"]["all_passed"]),
        }
        _save(result_path, payload)
        print(json.dumps({"result": str(result_path),
                          "historical_holdout": base.report["historical_holdout"],
                          "gate": base.report["gate"]}, ensure_ascii=False,
                         allow_nan=False))
        return 0
    except (ArchiveIntegrityError, DataIntegrityError) as exc:
        _save(failure_path, {
            "status": "data_failure; no strategy result accepted",
            "reason": str(exc),
            "preregistration_commit": "4ec84a3",
            "interpretation_commit": "2a9cbe9",
            "code_commit": commit,
            "started_utc": started,
            "finished_utc": datetime.now(timezone.utc).isoformat(),
        })
        print(f"Data integrity gate failed: {exc}")
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
